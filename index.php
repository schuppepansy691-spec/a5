        <div class="pupil-faq-accordion">
          <div class="faq-pantry-item active faq-pupil-item">
            <button class="faq-pupil-btn">How does pupil diameter affect optical depth of field and spherical aberration? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-pupil-content">
              In optical physics, a constricted pupil (miosis, 2.0 to 3.0 mm) increases optical depth of field by creating a pinhole aperture effect, blocking peripheral marginal light rays and minimizing higher-order spherical aberrations. Conversely, when the pupil dilates under dark conditions (mydriasis, 6.0 to 8.0 mm), peripheral corneal refractive errors cause light rays to focus at different focal planes, introducing spherical aberration while maximizing photon capture.
            </div>
          </div>
          <div class="faq-pupil-item">
            <button class="faq-pupil-btn">What are the afferent and efferent neural pathways of the Pupillary Light Reflex? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-pupil-content">
              The pupillary light reflex (PLR) operates via a four-neuron reflex arc. The afferent pathway begins at retinal photoreceptors (rods, cones, and ipRGCs), traveling along the optic nerve (Cranial Nerve II) to the pretectal nucleus in the midbrain. Interneurons project bilaterally to both Edinger-Westphal nuclei. The parasympathetic efferent pathway travels via the oculomotor nerve (Cranial Nerve III) to the ciliary ganglion, innervating the iris sphincter muscle to cause consensual pupillary constriction.
            </div>
          </div>
          <div class="faq-pupil-item">
            <button class="faq-pupil-btn">What is the clinical difference between Lower-Order and Higher-Order Aberrations? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-pupil-content">
              Lower-Order Aberrations (LOAs) account for approximately 85% to 90% of refractive errors and comprise 1st-order prism (tilt) and 2nd-order defocus (myopia/hyperopia) and astigmatism, easily correctable with standard spherical and cylindrical lenses. Higher-Order Aberrations (HOAs) represent complex 3rd to 6th-order optical distortions (coma, trefoil, spherical aberration) that degrade contrast sensitivity and cause nighttime halos, measurable exclusively via wavefront aberrometry.
            </div>
          </div>
          <div class="faq-pupil-item">
            <button class="faq-pupil-btn">How do ipRGC melanopsin photoreceptors control non-image-forming vision? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-pupil-content">
              Unlike classical rod and cone photoreceptors dedicated to high-resolution image formation, intrinsically photosensitive retinal ganglion cells (ipRGCs) constitute a specialized non-visual sensory network. Expressing the photopigment melanopsin with peak sensitivity at 480 nm, ipRGCs project directly to the suprachiasmatic nucleus (SCN) in the hypothalamus, regulating the human circadian master clock, melatonin suppression, and the sustained pupil light reflex.
            </div>
          </div>
